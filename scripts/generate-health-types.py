#!/usr/bin/env python3
"""Regenerate the public SDK catalogue; HealthKit has no enumerate-all-types API."""
import pathlib, re, subprocess
sdk = pathlib.Path(subprocess.check_output(['xcrun', '--sdk', 'iphoneos', '--show-sdk-path'], text=True).strip())
header = (sdk / 'System/Library/Frameworks/HealthKit.framework/Headers/HKTypeIdentifiers.h').read_text()
rows = []
for kind, name, version in re.findall(r'HK_EXTERN HK(Quantity|Category)TypeIdentifier const HK\1TypeIdentifier(\w+) API_AVAILABLE\(ios\(([\d.]+)\)', header):
    rows.append(f'        ("HK{kind}TypeIdentifier{name}", "{kind}", "{version}"),')
p = pathlib.Path('Pulso/Health/TypeRegistry.swift')
s = p.read_text().split('// BEGIN SDK CATALOGUE')[0]
s += '// BEGIN SDK CATALOGUE — generated by scripts/generate-health-types.py\n'
s += 'extension TypeRegistry {\n    static let sdkCatalogue: [(String, String, String)] = [\n' + '\n'.join(rows) + '\n    ]\n}\n'
p.write_text(s)
print(f'Generated {len(rows)} public quantity/category identifiers')
